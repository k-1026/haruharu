    # ---------- 부분 수정 ----------
    def 수정시작(self, 값):
        """'저녁만 다시 만들어 줘' 같은 요청. 새 버전을 만들고 다시 검사·검증한다. 이전 버전은 남는다."""
        if not isinstance(값, dict):
            raise ValueError('입력 형식을 확인하세요.')
        기획id = 값.get('기획id')
        with self.잠금:
            if self.작업 and self.작업.is_alive():
                raise ValueError('다른 작업이 진행 중입니다. 끝난 뒤 다시 요청하세요.')
            진행 = self.상태(기획id)
            if not 진행.get('기록id'):
                raise ValueError('기획 기록이 만들어진 코스만 부분 수정할 수 있습니다.')
            import 기획기록 as 기록모듈
            기록 = 기록모듈.읽기(self.runs, 진행['기록id'])
            안id = 값.get('안id') or 'A'
            if not 기록모듈.버전목록(기록, 안id):
                raise ValueError(f'없는 안: {안id}')
            유지, 바꿀, 요청 = 값.get('유지') or [], 값.get('바꿀') or [], 값.get('요청') or ''
            if not all(isinstance(x, list) for x in [유지, 바꿀]):
                raise ValueError('유지·바꿀 시간칸은 목록이어야 합니다.')
            폴더 = self._폴더(기획id)
            진행.update({'상태': '진행중', '안내': f'{안id}안 부분 수정: {str(요청)[:80]}', '완료시각': None})
            진행.setdefault('활동', []).append({'에이전트': '담당자', '하는일': f"부분 수정 요청 — 유지: {', '.join(유지) or '없음'} / 바꿀: {', '.join(바꿀)} / {str(요청)[:80]}",
                                            '시작': _지금(), '끝': _지금(), '상태': '완료'})
            _쓰기(폴더, 진행파일, 진행)
            self.현재id = 기획id
            self.작업 = threading.Thread(target=self._수정, args=(폴더, 진행, 기록, 안id, 유지, 바꿀, 요청), daemon=True)
            self.작업.start()
            return 진행

    def _수정(self, 폴더, 진행, 기록, 안id, 유지, 바꿀, 요청):
        import 처리기
        import 기획기록 as 기록모듈
        try:
            진행['활동'].append({'에이전트': '코스 검토 에이전트', '하는일': f'{안id}안에서 고를 칸만 다시 짜는 중', '시작': _지금(), '상태': '진행중'})
            진행['일하는중'] = {'에이전트': '코스 검토 에이전트', '하는일': f'{안id}안 {", ".join(바꿀)} 다시 짜는 중', '시작': _지금()}
            _쓰기(폴더, 진행파일, 진행)
            실행함수 = None if self.단계함수 is _기본단계함수 else self.단계함수
            된 = 처리기.부분수정(기록, 안id, self.runs, 유지, 바꿀, 요청, 실행함수)
            진행['활동'][-1].update({'상태': '완료' if 된 else '실패', '끝': _지금()})
            기록모듈.저장(기록, self.runs)
            if not 된:
                이유 = next((x['이유'] for x in reversed(기록['실행']) if x['결과'] == '실패'), '코스 에이전트가 수정본을 내지 못했습니다.')
                진행.update({'상태': '멈춤', '일하는중': None, '안내': '부분 수정 실패: ' + 이유[:200], '완료시각': _지금(), '정리': __import__('총괄').정리(기록)})
                return _쓰기(폴더, 진행파일, 진행)
            self._총괄(폴더, 진행, 기록, '수정본을 다시 검사하고 검증하고 있습니다.')
        except Exception as 오류:
            from 오류기록 import 저장, 안전문장
            진행['오류상세']=저장(폴더,오류,단계='부분 수정')
            이유 = str(오류) if isinstance(오류, (TimeoutError, ValueError)) and str(오류) else f'부분 수정 중 오류 ({type(오류).__name__})'
            진행.update({'상태': '멈춤', '일하는중': None, '안내': 안전문장(이유), '완료시각': _지금()})
            _쓰기(폴더, 진행파일, 진행)
