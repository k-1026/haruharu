def _지금():
    return datetime.now().astimezone().isoformat(timespec='seconds')


def _쓰기(폴더, 이름, 값):
    폴더.mkdir(parents=True, exist_ok=True)
    임시 = 폴더 / (이름 + '.tmp')
    임시.write_text(json.dumps(값, ensure_ascii=False, indent=2) if not isinstance(값, str) else 값, encoding='utf-8')
    임시.replace(폴더 / 이름)


def 입력_검사(값):
    """화면에서 받은 조건·목표·희망·동의를 검사해 정리한다."""
    if not isinstance(값, dict):
        raise ValueError('입력 형식을 확인하세요.')
    조건 = {'계절': 값.get('계절') or '', '언어권': 값.get('언어권') or [], '지역': 값.get('지역') or [],
          '체류기간': 값.get('체류기간') or ''}
    빠짐 = 빠진_조건(조건)
    if 빠짐:
        raise ValueError('빠진 조건: ' + ', '.join(빠짐))
    if 조건['계절'] not in 계절_선택지:
        raise ValueError('계절을 목록에서 고르세요.')
    if not isinstance(조건['언어권'], list) or any(x not in 언어권_선택지 for x in 조건['언어권']):
        raise ValueError('언어권을 목록에서 고르세요.')
    if not isinstance(조건['지역'], list) or any(x not in 지역_선택지 for x in 조건['지역']):
        raise ValueError('지역을 목록에서 고르세요.')
    if 조건['체류기간'] not in 화면_체류기간:
        raise ValueError('체류 기간은 당일 또는 1박2일을 고르세요.')
    조건['언어권'] = list(dict.fromkeys(조건['언어권']))
    조건['지역'] = list(dict.fromkeys(조건['지역']))
    목표 = 값.get('목표') or ''
    희망 = 값.get('희망') or []
    if not isinstance(목표, str) or len(목표) > 300:
        raise ValueError('목표는 300자 이내로 적어 주세요.')
    if not isinstance(희망, list) or len(희망) > 10 or any(not isinstance(x, str) or len(x) > 200 for x in 희망):
        raise ValueError('희망 사항은 10개까지, 각 200자 이내로 적어 주세요.')
    if 값.get('자동진행동의') is not True:
        raise ValueError('중간 알림·경고를 남기고 초안까지 진행하는 데 동의해야 시작할 수 있습니다.')
    return 조건, 목표.strip(), [x.strip() for x in 희망 if x.strip()]


def 빈_코스조건(체류):
    """담당자가 아직 정하지 않은 코스 조건. 모두 미정으로 두고 초안을 만든다(관리자실행.조건_검사 형식)."""
    칸들 = [(1, '점심'), (1, '저녁')] + ([(2, '점심')] if 체류 == '1박2일' else [])
    return {'시작일차': '미정', '종료일차': '미정', '시작지점': '', '종료지점': '', '시작시각': '', '종료시각': '',
            '운영방식': '', '치킨선택': '', '2일차오전구성': '' if 체류 == '1박2일' else '해당없음',
            '식사목록': [{'일차': d, '시간칸': k, '방식': '미선택', '식당': '', '식비포함': '미정'} for d, k in 칸들]}


async def _기본단계함수(에이전트, 입력):
    from run_stage import 단계_실행
    return await 단계_실행(에이전트, 입력)


class 기획실행:
    def __init__(self, 코스서비스, 단계함수=None):
        self.코스 = 코스서비스                 # 관리자실행.코스시험 (같은 객체를 써서 실행 중 작업을 함께 본다)
        self.runs = Path(코스서비스.저장소.루트)
        self.단계함수 = 단계함수 or _기본단계함수
        self.잠금 = threading.Lock()
        self.작업 = None
        self.현재id = None

    # ---------- 조회 ----------
    def _폴더(self, 기획id):
        if not isinstance(기획id, str):
            raise ValueError('기획을 선택하세요.')
        self.코스._원본(기획id)  # 형식·경로 검사 (<실행>/<회차>)
        return self.runs / 기획id

    def 상태(self, 기획id):
        폴더 = self._폴더(기획id)
        값 = json.loads((폴더 / 진행파일).read_text(encoding='utf-8'))
        if 값.get('상태') == '진행중' and not (self.현재id == 기획id and self.작업 and self.작업.is_alive()):
            값['상태'] = '중단됨'
            값['일하는중'] = None
            값['안내'] = '서버가 다시 켜져 실행이 끊겼습니다. 같은 조건으로 새 코스 만들기를 다시 눌러 주세요.'
        return 값

    def 최근(self):
        """가장 최근 기획의 진행 상황. 새로고침 뒤 화면이 이어서 보여 줄 때 쓴다."""
        파일들 = sorted(self.runs.glob('*/*/' + 진행파일), key=lambda p: p.parent.relative_to(self.runs).as_posix(), reverse=True)
        for p in 파일들:
            try:
                return self.상태(p.parent.relative_to(self.runs).as_posix())
            except (ValueError, OSError):
                continue
        return None

    # ---------- 시작 ----------
    def 시작(self, 값):
        조건, 목표, 희망 = 입력_검사(값)
        with self.잠금:
            if self.작업 and self.작업.is_alive():
                return {**self.상태(self.현재id), '중복': True}   # 버튼을 여러 번 눌러도 같은 기획을 돌려준다
            실행 = datetime.now().strftime('%Y%m%d_%H%M%S')
            기획id = f'{실행}/01회차'
            폴더 = self.runs / 실행 / '01회차'
            if 폴더.exists():
                raise ValueError('방금 시작한 기획이 있습니다. 잠시 뒤 다시 누르세요.')
            진행 = {'기획id': 기획id, '상태': '진행중', '시작시각': _지금(), '조건': 조건, '목표': 목표, '희망': 희망,
                  '자동진행동의': {'동의': True, '시각': _지금(), '범위': '1단계 알림·2단계 경고를 남기고 코스 초안까지. 확정·홍보·문서는 하지 않음'},
                  '단계': [{'이름': n, '상태': '대기', **단계담당[i]} for i, n in enumerate(단계이름)], '일하는중': None,
                  '안내': '자료를 확인하고 있습니다.',
                  '시험id': None, '기록id': None}
            _쓰기(폴더, 진행파일, 진행)
            self.현재id = 기획id
            self.작업 = threading.Thread(target=self._돌리기, args=(폴더, 진행), daemon=True)
            self.작업.start()
            return 진행

    # ---------- 실행 ----------
    def _부르기(self, 에이전트, 입력):
        결과 = self.단계함수(에이전트, 입력)
        return asyncio.run(결과) if inspect.isawaitable(결과) else 결과

    def _단계(self, 폴더, 진행, i, 상태, 안내=None):
        단계 = 진행['단계'][i]
        단계['상태'] = 상태
        단계['시각'] = _지금()
        if 상태 == '진행중':
            단계['시작'] = 단계['시각']
            진행['일하는중'] = {'에이전트': 단계['에이전트'], '하는일': 단계['하는일'], '시작': 단계['시각']}
        else:
            단계['끝'] = 단계['시각']
            진행['일하는중'] = None
        if 안내:
            진행['안내'] = 안내
        _쓰기(폴더, 진행파일, 진행)

    def _멈춤(self, 폴더, 진행, i, 이유):
        진행['단계'][i].update({'상태': '실패', '끝': _지금()})
        진행.update({'일하는중': None, '상태': '멈춤', '안내': 이유, '완료시각': _지금()})
        _쓰기(폴더, 진행파일, 진행)

    def _돌리기(self, 폴더, 진행):
        i = 0
        try:
            조건 = 진행['조건']
            # 1단계: 자료 확인
            self._단계(폴더, 진행, 0, '진행중', '자료를 확인하고 있습니다.')
            결과1 = self._부르기(STAGES[1]['에이전트'], '조건: ' + 조건_문장(조건))
            _쓰기(폴더, '1단계_결과.md', 결과1)
            _쓰기(폴더, '1단계_선택.json', {'조건': 조건, '담당자선택': '알림을남기고진행', '자동처리': 자동처리})
            self._단계(폴더, 진행, 0, '완료')

            # 2단계: 수요 근거 정리 → 3단계 전달 준비·검사
            i = 1
            self._단계(폴더, 진행, 1, '진행중', '수요 근거를 정리하고 있습니다.')
            기관 = '기관 데이터: 없음'
            결과2 = self._부르기(STAGES[2]['에이전트'], '1단계 결과:\n' + 결과1 + '\n\n담당자 선택: 알림을 남기고 진행\n' + 기관)
            _쓰기(폴더, '2단계_결과.md', 결과2)
            _쓰기(폴더, '2단계_선택.json', {'담당자선택_E3': '경고를남기고진행', '확정체류기간': 조건['체류기간'], '자동처리': 자동처리})
            전달 = 전달_준비(조건, 조건['체류기간'], '경고를남기고진행', 결과2, 기관)
            전달['담당자목표희망'] = {'목표': 진행['목표'], '희망': 진행['희망'],
                                '설명': '꼭 지킬 조건이 아니라 조정할 수 있는 바람. 지킬 수 없으면 이유를 남긴다'}
            문제 = 전달_검사(전달)
            전달['검사결과'] = 문제 or ['통과']
            _쓰기(폴더, '3단계_전달_준비.json', 전달)
            if 문제:
                return self._멈춤(폴더, 진행, 1, '수요 근거 결과를 코스 작성으로 넘길 수 없습니다: ' + '; '.join(문제[:3]))
            self._단계(폴더, 진행, 1, '완료')

            # 3단계: 코스 작성 (관리자 화면과 같은 실행·검사 사용)
            i = 2
            self._단계(폴더, 진행, 2, '진행중', '코스를 작성하고 있습니다. 몇 분 걸릴 수 있습니다.')
            시험 = self.코스.저장(진행['기획id'], 빈_코스조건(조건['체류기간']))
            진행['시험id'] = 시험['시험id']
            self.코스.시작(시험['시험id'])
            작업 = self.코스.작업들.get(시험['시험id'])
            if 작업:
                작업.join()
            결과 = self.코스.상태(시험['시험id'])
            if 결과.get('상태') in ['실행실패', '중단됨']:
                return self._멈춤(폴더, 진행, 2, 결과.get('안내') or '코스 작성에 실패했습니다.')
            self._단계(폴더, 진행, 2, '완료')

            # 결과 검사 요약 + 공유 기획 기록(A안 1버전) 만들기
            i = 3
            self._단계(폴더, 진행, 3, '진행중', '결과를 검사하고 기획 기록에 저장하고 있습니다.')
            from 기록가져오기 import 가져오기
            기록 = 가져오기(self.runs, 시험['시험id'], '사람:담당자(화면)', 목표=진행['목표'], 희망=진행['희망'])
            진행['기록id'] = 기록['기록id']
            남은 = (결과.get('문제') or []) + (결과.get('담당자확인대기') or []) + ((결과.get('시간표검사') or {}).get('충돌') or [])
            진행['검사'] = {'결과상태': 결과.get('상태'), '남은문제': 남은[:20]}
            self._단계(폴더, 진행, 3, '완료')
            진행.update({'상태': '완료', '완료시각': _지금(),
                       '안내': '코스 초안을 만들었습니다. ' + (f'확인할 것이 {len(남은)}건 있습니다. ' if 남은 else '') + '확정은 담당자가 합니다.'})
            _쓰기(폴더, 진행파일, 진행)
        except Exception as 오류:
            이유 = str(오류) if isinstance(오류, (TimeoutError, ValueError)) and str(오류) else \
                f'{단계이름[i]} 중 오류가 났습니다 ({type(오류).__name__}). AI 연결·로그인을 확인하고 다시 시작하세요.'
            self._멈춤(폴더, 진행, i, 이유)
