    # ---------- 조회 ----------
    def _폴더(self, 기획id):
        if not isinstance(기획id, str):
            raise ValueError('기획을 선택하세요.')
        self.코스._원본(기획id)  # 형식·경로 검사 (<실행>/<회차>)
        return self.runs / 기획id

    def 상태(self, 기획id):
        폴더 = self._폴더(기획id)
        값 = json.loads((폴더 / 진행파일).read_text(encoding='utf-8'))
        if 값.get('상태') == '진행중' and not (self.현재id == 기획id and self.작업 and self.작업.is_alive()):
            값['상태'] = '중단됨'
            값['일하는중'] = None
            값['안내'] = '서버가 다시 켜져 실행이 끊겼습니다. 같은 조건으로 새 코스 만들기를 다시 눌러 주세요.'
