        활동 = 진행.setdefault('활동', [])

        def 알림(종류, d):
            이름, 하는일 = 총괄.담당.get(d['행동'], ('총괄 에이전트', d['행동']))
            if 종류 == '시작':
                활동.append({'에이전트': 이름, '하는일': 하는일, '대상': d.get('대상', ''), '이유': d.get('이유', ''), '시작': _지금(), '상태': '진행중'})
                진행['일하는중'] = {'에이전트': 이름, '하는일': 하는일 + (f" ({d.get('대상')}안)" if d.get('행동') in ['코스', '점검', '검증'] else ''), '시작': 활동[-1]['시작']}
            else:
                활동[-1].update({'상태': '완료', '끝': _지금()})
                if d.get('결과'):
                    결 = d['결과']
