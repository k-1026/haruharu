최대대안 = 1        # 이번 단계에서는 B안 하나까지


def _안들(기록):
    return [a['안id'] for a in 기록모듈.맞추기(기록)['안'] if 기록모듈.버전목록(기록, a['안id'])]


def _경고(기록, 종류, 안id, 버전):
    return [x for x in 기록['경고'] if x.get('종류') == 종류 and x.get('안id') == 안id and x.get('버전', 1) == 버전]


def _검사후_수집함(기록, 안id):
    마지막검증 = max((i for i, x in enumerate(기록['실행']) if x['에이전트'] == '에이전트:검증' and str(x['대상']).startswith(f'{안id}안')), default=-1)
    return any(x['에이전트'] == '에이전트:수집' for x in 기록['실행'][마지막검증 + 1:])


def 다음_할일(기록):
    """규칙 총괄. AI 총괄이 답하지 못할 때 쓰고, AI가 고른 일이 허용되는지 볼 때도 쓴다."""
    안들 = _안들(기록)
    if not 안들:
        return {'행동': '코스', '대상': 'A', '이유': '코스안이 아직 없음'}
    for 안id in 안들:
        버전 = max(기록모듈.버전목록(기록, 안id))
        if not _경고(기록, '코드점검', 안id, 버전):
            return {'행동': '점검', '대상': 안id, '이유': f'{안id}안 {버전}버전 코드 검사 전'}
        결과 = _경고(기록, '검증결과', 안id, 버전)
        if not 결과:
            return {'행동': '검증', '대상': 안id, '이유': f'{안id}안 {버전}버전 독립 검증 전'}
        분류 = 최신분류(기록, 안id, 버전)
        검증반려 = not 결과[-1].get('통과')
        담당자문제 = [x['문구'] for x in _경고(기록, '검증', 안id, 버전) if x.get('되돌릴곳') == '담당자']
        # 담당자 문제가 섞여 있어도, 에이전트가 풀 수 있는 수집·코스 문제는 먼저 처리한다
        if 분류['자료보완'] and not _검사후_수집함(기록, 안id) and 검증반려:
            return {'행동': '수집', '대상': '; '.join(x['문구'] for x in 분류['자료보완'])[:300],
                    '이유': f'{안id}안 {버전}버전 검증에서 자료 부족'}
        # 코스를 다시 쓰는 경우: AI가 고칠 것이 있거나, 수집한 후보를 코스에 반영할 때. 담당자 문제만 남았으면 다시 쓰지 않는다
        후보반영 = 분류['자료보완'] and _검사후_수집함(기록, 안id) and any(x.get('상태') in ['후보', '승인'] for x in 기록['후보'])
        if (분류['AI수정'] or 후보반영) and 버전 < 최대버전:
            고칠것 = [x['문구'] for x in 분류['AI수정']] or [x['문구'] for x in _경고(기록, '검증', 안id, 버전)]
            return {'행동': '코스', '대상': 안id, '지시': '; '.join(고칠것)[:500],
                    '이유': f'{안id}안 {버전}버전 고칠 것: ' + '; '.join(고칠것)[:200]}
    다씀 = [a for a in 안들 if max(기록모듈.버전목록(기록, a)) >= 최대버전]
    이유 = f"{', '.join(a + '안' for a in 다씀)}은 최대 {최대버전}버전까지 고쳐 써서 더 고치지 않음. 남은 문제는 담당자에게" if 다씀         else '남은 것은 담당자가 정할 일'
    return {'행동': '담당자에게', '대상': 안들[0], '이유': 이유}


def 상황(기록):
    """AI 총괄에게 줄 요약. 코스 원문 대신 검사 결과와 희망 반영만 준다(입력을 짧게)."""
    기록모듈.맞추기(기록)
    한도 = {**기록모듈.기본한도, **기록.get('한도', {})}
    쓴호출 = sum(int(x.get('AI호출', 0)) for x in 기록['실행'])
    안목록 = []
    for a in 기록['안']:
        버전들 = 기록모듈.버전목록(기록, a['안id'])
        if not 버전들:
            continue
        v = max(버전들)
        코스 = 처리기.최신안(기록, a['안id'])['코스']
        안목록.append({'안id': a['안id'], '설명': a.get('설명', ''), '바꾼희망': a.get('바꾼희망', {}), '최신버전': v,
                    '검사': {k: [x['문구'] for x in 묶음] for k, 묶음 in 최신분류(기록, a['안id'], v).items()},
                    '검증': 기록모듈.검증상태(기록, a['안id'], v)['검증'],
                    '희망반영': 코스.get('희망반영') or [], '버전수': len(버전들),
                    '장소': [f"{r.get('일차')}일차 {r.get('시간칸')}: {r.get('장소명')}" for r in 코스.get('칸목록') or []][:20]})
    대안수 = len(기록['안']) - 1
    할수있는 = ['코스', '수집', '점검', '검증', '담당자에게'] + (['대안'] if 대안수 < 최대대안 and 기록.get('희망') else [])
    return {'원래요청': 기록['원래요청'], '희망': 기록.get('희망', []), '안목록': 안목록,
            '남은한도': {'AI호출': max(0, 한도['AI호출'] - 쓴호출), '안별최대버전': 최대버전},
            '최근결정': [{'행동': x['행동'], '요약': x['요약']} for x in 기록['결정이력'][-6:]],
            '할수있는일': 할수있는}


def _검사(기록, d, 상황값):
    """AI가 고른 일이 지금 할 수 있는 일인지 코드로 확인한다. 안 되면 이유를 돌려준다."""
    행동 = d.get('행동')
    if 행동 not in 상황값['할수있는일']:
        return f'지금 고를 수 없는 일: {행동}'
    안들 = [a['안id'] for a in 상황값['안목록']]
    if 행동 in ['코스', '점검', '검증'] and d.get('대상') not in 안들:
        return f"없는 안: {d.get('대상')}"
    if 행동 == '코스' and next(a for a in 상황값['안목록'] if a['안id'] == d['대상'])['버전수'] >= 최대버전:
        return f"{d['대상']}안은 이미 {최대버전}버전까지 고쳐 씀"
    if 행동 == '대안':
        바꿀 = d.get('바꿀희망')
        if not isinstance(바꿀, dict) or not 바꿀:
            return '대안에는 바꿀 희망이 필요함'
        없는 = [k for k in 바꿀 if not any(h['id'] == k for h in 기록.get('희망', []))]
        if 없는:
            return f'없는 희망: {없는}'
        if not str(d.get('이유', '')).strip():
            return '대안에는 바꾸는 이유가 필요함'
    if 행동 == '수집' and not str(d.get('지시') or d.get('대상') or '').strip():
        return '수집할 내용이 비어 있음'
    return ''


def AI_다음_할일(기록, 실행함수=None):
    """AI 총괄에게 묻고, 답이 규칙에 맞지 않으면 규칙 총괄로 돌아간다. 돌아간 이유는 결정에 남긴다."""
    상황값 = 상황(기록)
    # 새 버전·검증·후보가 생기면 새 판단이다. 호출 수와 실패 이력만 바뀌면 같은 판단이다.
    판단자료 = {k: v for k, v in 상황값.items() if k not in ['최근결정', '남은한도']}
    판단자료['후보'] = 기록['후보']
    식별 = hashlib.sha256(json.dumps(판단자료, ensure_ascii=False, sort_keys=True).encode('utf-8')).hexdigest()[:16]
    대상 = f'다음 할 일 · 상태 {식별}'
    값 = 호출(기록, '에이전트:총괄', 총괄지침, '판단', 대상, 상황값, '다음 할 일 고르기', 실행함수)
    if 값 is None and 기록['실행'] and 'JSON 없음' in 기록['실행'][-1]['이유']:
        # 설명만 하고 JSON을 빠뜨린 경우 한 번만 다시 묻는다(한도 검사는 호출이 다시 한다)
        값 = 호출(기록, '에이전트:총괄', 총괄지침, '판단', 대상, {**상황값, '다시요청': '설명 없이 출력 형식의 JSON 블록 하나만 내세요.'},
                 '다음 할 일 고르기 (JSON 없어 다시 요청)', 실행함수)
    if 값 is None:
        d = 다음_할일(기록)
        return {**d, '판단': '규칙', '이유': d['이유'] + ' (AI 총괄 응답 없음 → 규칙으로 판단)'}
    문제 = _검사(기록, 값, 상황값)
    if 문제:
        d = 다음_할일(기록)
        return {**d, '판단': '규칙', '이유': d['이유'] + f' (AI 총괄 답 거부: {문제})'}
    return {'행동': 값['행동'], '대상': str(값.get('대상') or (상황값['안목록'][0]['안id'] if 상황값['안목록'] else 'A')),
            '지시': str(값.get('지시') or ''), '바꿀희망': 값.get('바꿀희망') or {}, '이유': str(값.get('이유') or ''), '판단': 'AI'}


def _보완요청(기록, 안id, 지시=''):
    if 안id not in _안들(기록):
        return [지시] if 지시 else []
    v = max(기록모듈.버전목록(기록, 안id))
    분류 = 최신분류(기록, 안id, v)
    수집 = [f"후보: {x.get('이름')} ({x.get('출처ID')})" for x in 기록['후보'] if x.get('상태') in ['후보', '승인']]
    return ([지시] if 지시 else []) + [x['문구'] for x in 분류['AI수정'] + 분류['자료보완']] + 수집


def _다음안id(기록):
    있는 = {a['안id'] for a in 기록['안']}
    return next(c for c in 'BCDEFGHIJKLMNOPQRSTUVWXYZ' if c not in 있는)


def 한걸음(기록, d, runs루트, 실행함수=None):
    """고른 일 하나를 실행한다. 돌려주는 값: 실행한 에이전트 이름(화면 표시용)."""
    행동, 대상 = d['행동'], d.get('대상', '')
    if 행동 == '코스':
        처리기.코스짜기(기록, 대상, runs루트, _보완요청(기록, 대상, d.get('지시', '')), 실행함수)
    elif 행동 == '수집':
        처리기.수집하기(기록, d.get('지시') or 대상, 실행함수)
    elif 행동 == '점검':
        기록도구.코스_점검(기록, 대상, 입력=처리기.코스입력(기록, 대상, runs루트, []))
    elif 행동 == '검증':
        처리기.검증하기(기록, 대상, 실행함수)
    elif 행동 == '대안':
        안id = _다음안id(기록)
        바꾼 = ', '.join(f"{h['내용']} → {d['바꿀희망'][h['id']]}" for h in 기록['희망'] if h['id'] in d['바꿀희망'])
        기록모듈.안_추가(기록, 안id, f'희망을 바꾼 대안: {바꾼}'[:200], '에이전트:총괄', 바꾼희망=d['바꿀희망'], 이유=d.get('이유', ''))
        d['대상'] = 안id
        처리기.코스짜기(기록, 안id, runs루트, [], 실행함수)


담당 = {'코스': ('코스 검토 에이전트', '코스를 다시 쓰는 중'), '수집': ('자료 수집 에이전트', '저장소 자료에서 후보를 찾는 중'),
      '점검': ('검사 도구 (코드)', '시간표·형식·요일을 검사하고 문제를 나누는 중'), '검증': ('검증 에이전트', '만든 쪽과 따로 코스를 점검하는 중'),
      '대안': ('코스 검토 에이전트', '희망을 바꾼 대안(B안)을 만드는 중'), '판단': ('총괄 에이전트', '다음에 할 일을 고르는 중')}


def 돌리기(기록, runs루트, 실행함수=None, 최대단계=20, 저장=False, AI판단=False, 알림=None, 빠른진행=False):
    """다음 할 일을 고르고 실행하기를 되풀이한다. 알림(종류, 내용)으로 화면에 진행을 알린다."""
    알림 = 알림 or (lambda *a: None)
    steps = []
    for _ in range(최대단계):
        규칙 = 다음_할일(기록)
        if AI판단 and not (빠른진행 and 규칙['행동'] in ['점검', '검증']):
            알림('시작', {'행동': '판단'})
            d = AI_다음_할일(기록, 실행함수)
            알림('끝', {'행동': '판단', '결과': d})
        else:
            d = 규칙
        if d['행동'] not in 행동목록:
            d = {'행동': '담당자에게', '대상': '', '이유': f"허용되지 않은 행동: {d['행동']}"}
        steps.append(d)
        기록['결정이력'].append({'시각': 기록모듈._지금(), '작성자': '에이전트:총괄', '행동': '결정', '영역': d['행동'],
                             '대상id': d.get('대상', ''), '근거': d.get('판단', '규칙'), '요약': d.get('이유', '')[:200]})
        if d['행동'] == '담당자에게':
            break
        n = len(기록['실행'])
        알림('시작', d)
        한걸음(기록, d, runs루트, 실행함수)
        알림('끝', d)
        if 저장:
            기록모듈.저장(기록, runs루트)
        보류 = [x for x in 기록['실행'][n:] if x['결과'] == '보류']
        if 보류:
            steps.append({'행동': '담당자에게', '대상': d.get('대상', ''), '이유': 보류[-1]['이유']})
            break
        실패 = [x for x in 기록['실행'][n:] if x['결과'] == '실패']
        if 실패 and d['행동'] in ['대안']:
            steps.append({'행동': '담당자에게', '대상': d.get('대상', ''), '이유': '대안 작성 실패: ' + 실패[-1]['이유'][:150]})
            break
    else:
        steps.append({'행동': '담당자에게', '대상': '', '이유': f'최대 {최대단계}단계 도달'})
    last = steps[-1]
    기록['결정이력'].append({'시각': 기록모듈._지금(), '작성자': '에이전트:총괄', '행동': '담당자에게', '영역': '',
                         '대상id': last.get('대상', ''), '근거': ' → '.join(s['행동'] for s in steps), '요약': last.get('이유', '')})
    if 저장:
        기록모듈.저장(기록, runs루트)
    return steps


def 정리(기록):
    """화면·마지막 검토용: 안별 최신 버전의 설명·희망 반영·세 가지 분류와 사람이 정할 것 모음."""
    안들 = []
    사람 = []
    for a in 기록모듈.맞추기(기록)['안']:
        버전들 = 기록모듈.버전목록(기록, a['안id'])
        if not 버전들:
            continue
        v = max(버전들)
        코스 = 처리기.최신안(기록, a['안id'])['코스']
        분류 = 최신분류(기록, a['안id'], v)
        안들.append({'안id': a['안id'], '설명': a.get('설명', ''), '바꾼희망': a.get('바꾼희망', {}), '이유': a.get('이유', ''),
                   '버전': v, '버전들': 버전들, '검증': 기록모듈.검증상태(기록, a['안id'], v)['검증'], '분류': 분류,
                   '대안설명': 코스.get('대안설명'), '희망반영': 코스.get('희망반영') or [],
                   '필수조건반영': 필수조건반영(코스, 기록모듈.적용조건(기록, a['안id'])['조건'])})
        사람 += [f"[{a['안id']}안] {x['문구']}" for x in 분류['사람결정']]
    return {'안': 안들, '사람이정할것': list(dict.fromkeys(사람)), '선택': 기록.get('선택')}


def 모의응답():
    """AI 없이 흐름을 보여 주는 정해진 응답: 검증 첫 번째는 자료 부족으로 반려, 두 번째는 통과."""
    횟수 = {'검증': 0}

    def fn(지침, 입력글):
        if 지침.endswith('코스검토.md'):
            return json.dumps({'칸목록': [], '식사목록': [], '메모': '모의 코스'}, ensure_ascii=False)
        if 지침.endswith('자료수집.md'):
            return json.dumps({'후보': [{'이름': '향촌문화관(모의)', '종류': '관광지', '내용': '모의 응답', '출처ID': 'S70', '출처등급': '공식'}], '못찾음': []}, ensure_ascii=False)
        횟수['검증'] += 1
        if 횟수['검증'] == 1:
            return json.dumps({'통과': False, '문제': [{'종류': '운영', '대상': '밤', '내용': '평일 밤 후보 없음(모의)', '되돌릴곳': '수집'}]}, ensure_ascii=False)
        return '{"통과":true,"문제":[]}'
    return fn


