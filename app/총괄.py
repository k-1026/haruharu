"""총괄: 공유 기획 기록을 보고 다음 할 일을 정하고, 처리기를 부르고, 부족하면 되돌린다.

- AI 총괄(.claude/agents/총괄.md)이 다음 할 일을 고른다. 응답이 없거나 규칙에 어긋나면 규칙 총괄(다음_할일)이 대신 고른다.
- 무엇을 고르든 실행·한도·권한 검사는 코드(처리기·기획기록)가 한다. 총괄 자신의 AI 호출도 한도에 들어간다.
- 할 수 있는 일: 코스(다시 쓰기) · 수집 · 점검 · 검증 · 대안(희망을 바꾼 새 안) · 담당자에게(마침).
사용: python 총괄.py <기록id> [--모의]
"""
