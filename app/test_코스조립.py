def 칸(코스, id):
    return next(r for r in 코스['칸목록'] if r['칸ID'] == id)


class 안조립시험(unittest.TestCase):
    def 조립(self, 입력=None, 주문=None, 고정=None):
        입력 = 입력 or 시험입력()
        return 코스조립.안_조립((주문 or 정상주문())['A'], 후보(입력), 입력, '공통', 고정)

    def test_시각은_시작부터_머무는시간과_이동분으로_이어진다(self):
        코스 = self.조립()
        self.assertEqual(칸(코스, '낮-1')['시각'], {'값': '10:00', '종류': '가정'})
        self.assertEqual(칸(코스, '낮-1')['종료시각'], {'값': '11:30', '종류': '가정'})
        self.assertEqual(칸(코스, '점심-1')['시각'], {'값': '11:41', '종류': '가정'})
        self.assertEqual(칸(코스, '낮-2')['시각'], {'값': '13:01', '종류': '가정'})

    def test_담당자_시작시각이면_확정(self):
        입력 = 시험입력(); 입력['코스작성조건']['시작시각'] = '09:30'
        코스 = self.조립(입력)
        self.assertEqual(칸(코스, '낮-1')['시각'], {'값': '09:30', '종류': '확정'})
        self.assertEqual(칸(코스, '점심-1')['시각']['종류'], '가정')

