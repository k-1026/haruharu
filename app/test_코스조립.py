class 주문서검사시험(unittest.TestCase):
    def 검사(self, 주문, 입력=None, 한안=False):
        입력 = 입력 or 시험입력()
        return 코스조립.주문서_검사(주문, 후보(입력), 입력, 한안)

    def test_설명문이_섞인_주문서도_읽는다(self):
        글 = '네, 만들었습니다\n```json\n' + json.dumps(정상주문(), ensure_ascii=False) + '\n```\n끝'
        self.assertEqual(코스조립.주문서_읽기(글)['A']['칸'][0]['장소'], 'P1')

    def test_없는_P번호는_문제(self):
        주문 = 정상주문(); 주문['A']['칸'][0]['장소'] = 'P99'
        self.assertIn('A 낮-1: 후보표에 없는 장소 P99', self.검사(주문))

    def test_없는_근거ID는_문제(self):
        주문 = 정상주문(); 주문['A']['칸'][0]['근거'] = ['R999']
        self.assertIn('A 낮-1: 없는 근거ID R999', self.검사(주문))

    def test_없는_운영주체는_문제(self):
        주문 = 정상주문(); 주문['A']['칸'][0]['운영'] = ['O99']
        self.assertIn('A 낮-1: 없는 운영주체 O99', self.검사(주문))

    def test_칸ID_중복은_문제(self):
        주문 = 정상주문(); 주문['A']['칸'].append(copy.deepcopy(주문['A']['칸'][0]))
        self.assertIn('A: 칸ID 중복 낮-1', self.검사(주문))

    def test_당일인데_2일차는_문제(self):
        입력 = 시험입력('당일'); 주문 = 정상주문()
        self.assertIn('A 낮-3: 당일 코스에 2일차', self.검사(주문, 입력))

    def test_B안이_없는_칸을_가리키면_문제(self):
        주문 = 정상주문(); 주문['B']['뺀칸'] = ['밤-9']
        self.assertIn('B: A안에 없는 칸 밤-9', self.검사(주문))

    def test_가족코스에_술_표현은_문제(self):
        입력 = 시험입력(); 입력['조건']['동행'] = '가족'
        주문 = 정상주문(); 주문['A']['칸'][3]['이유'] = '치맥으로 마무리'
        self.assertIn('A 저녁-1: 가족 코스에 술 표현', self.검사(주문, 입력))

    def test_동행정보가_없으면_술검사를_하지_않는다(self):
        주문 = 정상주문(); 주문['A']['칸'][3]['이유'] = '치맥으로 마무리'
        self.assertEqual(self.검사(주문), [])

    def test_B가_null이면_대안불가이유가_필요(self):
        주문 = 정상주문(); 주문['B'] = None
        self.assertIn('B: 대안불가이유 필요', self.검사(주문))

    def test_한안_주문서는_안_키를_본다(self):
        self.assertEqual(self.검사({'안': 정상주문()['A']}, 한안=True), [])
        self.assertIn('주문서에 안이 없음', self.검사(정상주문(), 한안=True))

    def test_정상_주문서는_통과(self):
        self.assertEqual(self.검사(정상주문()), [])


