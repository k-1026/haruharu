def 이름들(표):
    return [r['장소명'] for r in 표['장소'].values()]


class 후보표시험(unittest.TestCase):
    def test_고른_구_밖_장소는_빠진다(self):
        self.assertNotIn('평화시장 닭똥집골목 (치킨 옵션)', 이름들(후보(시험입력(치킨='선택'))))

    def test_치킨_미선택이면_치킨옵션_장소가_빠진다(self):
        self.assertFalse([n for n in 이름들(후보()) if '(치킨 옵션)' in n])
        self.assertIn('뉴욕통닭 (치킨 옵션)', 이름들(후보(시험입력(치킨='선택'))))

    def test_상태가_미입력이어도_후보에_남는다(self):
        표 = 후보()
        행 = [r for r in 표['장소'].values() if r['장소명'] == '근대골목']
        self.assertEqual(len(행), 1)
        self.assertEqual(행[0]['상태'], '미입력')

    def test_후보표는_데이터가_커져도_상한을_지킨다(self):
        작은 = 후보()
        큰행 = []
        for i in range(20):
            for r in 시험장소():
                r = dict(r, 순번=str(int(r['순번']) + 100 * i), 장소명=r['장소명'] + ('' if i == 0 else f' {i}'))
                큰행.append(r)
        큰 = 후보(장소행=큰행)
        self.assertEqual(len(큰['장소']), 30)
        self.assertLessEqual(len(작은['장소']), 30)
        import re
        장소줄 = lambda 표: [줄 for 줄 in 코스조립.후보표_글(표).splitlines() if re.match(r"P\d+'*\|", 줄)]
        self.assertEqual(len(장소줄(큰)), 30)

    def test_이전코스_장소는_항상_후보에_들어간다(self):
        이전 = {'칸목록': [{'칸ID': '낮-1', '장소명': '대구광역시 중구 향촌문화관'}]}
        표 = 후보(이전=이전, 상한=3)
        self.assertEqual(len(표['장소']), 3)
        self.assertIn('향촌문화관', 이름들(표))

    def test_이동은_괄호앞_이름으로_맞추고_모호하면_뺀다(self):
        표 = 후보(시험입력(치킨='선택'))
        p = {r['장소명']: k for k, r in 표['장소'].items()}
        쌍 = {(x['출발'], x['도착']) for x in 표['이동']}
        self.assertIn((p['김광석길'], p['뉴욕통닭 (치킨 옵션)']), 쌍)
        모호 = 시험장소() + [장소(99, '서문시장 (2지구)', 칸='점심', 유형='시장')]
        표 = 후보(장소행=모호)
        self.assertFalse([x for x in 표['이동'] if '서문시장' in (표['장소'][x['출발']]['장소명'], 표['장소'][x['도착']]['장소명'])])
        self.assertIn('서문시장', 표['이름대응불명확'])

    def test_근거는_40줄까지_코드근거추출_우선(self):
        입력 = 시험입력()
        입력['근거목록'] = [근거(n) for n in range(1, 130)]
        입력['코드근거추출'] = {'전체근거행수': 129, 'AI전달근거ID': ['R05']}
        표 = 후보(입력)
        self.assertLessEqual(len(표['근거']), 40)
        self.assertEqual(표['근거'][0]['근거ID'], 'R05')

    def test_운영주체표를_읽는다(self):
        표 = 코스조립.운영주체표_읽기(저장소 / '지침/3_코스검토/11_운영주체_후보.md')
        번호 = [x['O번호'] for x in 표]
        self.assertIn('O1', 번호)
        self.assertIn('O8', 번호)
        self.assertEqual(len(번호), len(set(번호)))


