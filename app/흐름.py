"""1 → 2단계 흐름에 쓰는 순수 함수 (입력 검사 · 3단계 전달 준비 · 검사).

에이전트 호출 없이 시험할 수 있게 orchestrator.py에서 분리했다.
규칙: 지침/공통/단계_넘김.md 3 · 4 · 5장, inventory/유저플로우_v1.md 1 · 4-1 · 5-1.
"""

import re

계절_선택지 = ["봄", "여름", "가을", "겨울"]
계절_월 = {"봄": [3, 4, 5], "여름": [6, 7, 8], "가을": [9, 10, 11], "겨울": [1, 2, 12]}
언어권_선택지 = ["영어권", "일본어", "중국어 간체", "중국어 번체"]
지역_선택지 = ["중구", "동구"]  # 지침/공통/데이터_목록.md 2장 "지역" 표에 자료가 있는 구만
체류기간_선택지 = ["당일", "1박2일", "추천받기"]
확정체류기간_선택지 = ["당일", "1박2일"]

필수_조건 = ["계절", "언어권", "지역", "체류기간"]


def 빠진_조건(조건: dict) -> list[str]:
    """비어 있는 필수 조건 이름 목록. 지역도 기본값 없이 빠짐으로 본다."""
    빠짐 = []
    for 이름 in 필수_조건:
        값 = 조건.get(이름)
        if 값 is None or 값 == "" or 값 == []:
            빠짐.append(이름)
    return 빠짐


def 조건_문장(조건: dict) -> str:
    """에이전트에 줄 조건 한 줄. 지역은 목록."""
    return (
        f"방문객: 외국인 · 계절: {조건['계절']} (월 {계절_월[조건['계절']]}) · "
        f"언어권: {', '.join(조건['언어권'])} · 지역: {', '.join(조건['지역'])} · "
        f"체류 기간: {조건['체류기간']}"
    )


def 확정체류기간_정하기(조건: dict, 담당자_선택: str | None) -> str:
    """추천받기가 아니면 조건 그대로, 추천받기면 담당자가 고른 값. 없으면 '미선택'."""
    if 조건["체류기간"] != "추천받기":
        return 조건["체류기간"]
    return 담당자_선택 if 담당자_선택 in 확정체류기간_선택지 else "미선택"


_R = re.compile(r"\bR\d{2,}\b")
_W = re.compile(r"\bW\d+\b")


def 근거_경고_추출(결과2: str) -> tuple[set[str], dict[str, set[str]]]:
    """2단계 결과 글에서 근거 ID 집합과 {경고 ID: 적용 근거 ID 집합}을 뽑는다.

    근거 ID: 근거표 행 맨 앞 칸 (| R01 |).
    경고: '(적용 근거: R01 · R02)'가 붙은 [W1 …] 줄.
    """
    근거 = set(re.findall(r"^\|\s*(R\d{2,})\s*\|", 결과2, re.M))
    경고: dict[str, set[str]] = {}
    for 줄 in 결과2.splitlines():
        m = re.search(r"\[(W\d+)[^\]]*\]", 줄)
        if m and "적용 근거" in 줄:
            적용부분 = 줄.split("적용 근거", 1)[1]
            경고.setdefault(m.group(1), set()).update(_R.findall(적용부분))
    return 근거, 경고


def 전달_준비(조건: dict, 확정체류기간: str, 선택_E3: str, 결과2: str, 기관데이터: str) -> dict:
    """3단계로 넘길 입력 (단계_넘김.md 4장의 초안 필드). 실제 3단계 호출은 아직 연결 전."""
    근거, 경고 = 근거_경고_추출(결과2)
    return {
        "단계": 2,
        "조건": {
            "방문객": "외국인",
            "시기": 계절_월[조건["계절"]],
            "계절": 조건["계절"],
            "언어권": list(조건["언어권"]),
            "지역": list(조건["지역"]),
            "체류기간": 조건["체류기간"],
        },
        "확정체류기간": 확정체류기간,
        "담당자선택_E3": 선택_E3,
        "근거ID목록": sorted(근거),
        "경고목록": [{"경고ID": w, "적용근거ID": sorted(r)} for w, r in sorted(경고.items())],
        "2단계결과_원문": 결과2,
        "기관데이터": 기관데이터,
        "대구도착출발지점": "미확보",
        "담당자판단": {"채택근거ID": [], "비고": "초안 · 3단계 담당과 공동 확인 전"},
        "필드상태": "초안 (단계_넘김.md 4장, 3단계 담당과 형식 합의 전)",
    }


def 전달_검사(전달: dict) -> list[str]:
    """문제 목록. 빈 목록이면 통과. 단계_넘김.md 5장 중 지금 검사할 수 있는 것만."""
    문제 = []
    for 칸 in ["조건", "확정체류기간", "담당자선택_E3", "근거ID목록", "경고목록", "2단계결과_원문"]:
        if 칸 not in 전달:
            문제.append(f"필수 필드 없음: {칸}")
    if 문제:
        return 문제
    빠짐 = 빠진_조건({**전달["조건"]})
    if 빠짐:
        문제.append("조건 누락: " + ", ".join(빠짐))
    if 전달["확정체류기간"] not in 확정체류기간_선택지:
        문제.append("확정 체류 기간 미선택 — 3단계를 시작하지 않고 담당자에게 되묻는다")
    if 전달["담당자선택_E3"] != "경고를남기고진행":
        문제.append("2단계 담당자 선택(E3) 미선택 — 3단계를 시작하지 않는다")
    if not 전달["근거ID목록"]:
        문제.append("근거 ID를 찾지 못함 — 근거표에 R01 … 이 있는지 확인")
    근거 = set(전달["근거ID목록"])
    for 경고 in 전달["경고목록"]:
        if not 경고["적용근거ID"]:
            문제.append(f"{경고['경고ID']}: 적용 근거 ID 없음")
        없음 = [r for r in 경고["적용근거ID"] if r not in 근거]
        if 없음:
            문제.append(f"{경고['경고ID']}: 근거표에 없는 근거 ID {', '.join(없음)}")
    return 문제
