"""1 → 2단계 흐름에 쓰는 순수 함수 (입력 검사 · 2단계 결과 읽기 · 3단계 전달 준비 · 검사).

에이전트 호출 없이 시험할 수 있게 orchestrator.py에서 분리했다.
규칙: 지침/공통/단계_넘김.md 3 · 4 · 5장, 지침/2_수요근거/출력.md, inventory/유저플로우_v1.md.
"""

import re

계절_선택지 = ["봄", "여름", "가을", "겨울"]
계절_월 = {"봄": [3, 4, 5], "여름": [6, 7, 8], "가을": [9, 10, 11], "겨울": [1, 2, 12]}
언어권_선택지 = ["영어권", "일본어", "중국어 간체", "중국어 번체"]
지역_선택지 = ["중구", "동구"]  # 지침/공통/데이터_목록.md 2장 "지역" 표에 자료가 있는 구만
체류기간_선택지 = ["당일", "1박2일", "추천받기"]
확정체류기간_선택지 = ["당일", "1박2일"]

필수_조건 = ["계절", "언어권", "지역", "체류기간"]

# 2단계 근거표 열 이름 (지침/2_수요근거/출력.md 화면 표) → 전달 JSON 필드 (단계_넘김.md 4장)
근거표_열 = {
    "ID": "근거ID",
    "항목": "항목",
    "원자료 항목명": "원자료항목명",
    "수치": "수치_원문",
    "파일 · 행 위치": "파일_행위치",
    "출처": "출처",
    "연도": "연도",
    "표본 · 대상": "표본_대상",
    "한계": "한계",
    "경고": "경고",
}
근거_필수 = ["근거ID", "항목", "수치_원문", "출처", "파일_행위치"]

_R = re.compile(r"\bR\d{2,}\b")


def 빠진_조건(조건: dict) -> list[str]:
    """비어 있는 필수 조건 이름 목록. 지역도 기본값 없이 빠짐으로 본다."""
    return [이름 for 이름 in 필수_조건 if 조건.get(이름) in (None, "", [])]


def 조건_문장(조건: dict) -> str:
    """에이전트에 줄 조건 한 줄. 지역은 목록."""
    return (
        f"방문객: 외국인 · 계절: {조건['계절']} (월 {계절_월[조건['계절']]}) · "
        f"언어권: {', '.join(조건['언어권'])} · 지역: {', '.join(조건['지역'])} · "
        f"체류 기간: {조건['체류기간']}"
    )


def 확정체류기간_정하기(조건: dict, 담당자_선택: str | None) -> str:
    """추천받기가 아니면 조건 그대로, 추천받기면 담당자가 고른 값. 없으면 '미선택'."""
    if 조건["체류기간"] != "추천받기":
        return 조건["체류기간"]
    return 담당자_선택 if 담당자_선택 in 확정체류기간_선택지 else "미선택"


# ---------- 2단계 결과 글 읽기 ----------

def 절_꺼내기(글: str, 제목: str) -> str:
    """'## 제목' 아래부터 다음 '## ' 전까지."""
    m = re.search(rf"^##\s*{re.escape(제목)}[^\n]*\n(.*?)(?=^##\s|\Z)", 글, re.M | re.S)
    return m.group(1).strip() if m else ""


def _칸(줄: str) -> list[str]:
    return [c.strip() for c in 줄.strip().strip("|").split("|")]


def _숫자(원문: str):
    """'59.5%' · '2,514명' → 숫자. 숫자가 하나가 아니면 '미확인'."""
    수 = re.findall(r"-?\d[\d,]*(?:\.\d+)?", 원문)
    if len(수) != 1:
        return "미확인"
    값 = 수[0].replace(",", "")
    return float(값) if "." in 값 else int(값)


def 근거표_읽기(글: str) -> list[dict]:
    """근거표 절의 표를 행 객체 목록으로. 머리 행의 열 이름으로 필드를 정한다."""
    표 = [줄 for 줄 in 절_꺼내기(글, "근거표").splitlines() if 줄.strip().startswith("|")]
    if len(표) < 2:
        return []
    머리 = _칸(표[0])
    행들 = []
    for 줄 in 표[1:]:
        칸 = _칸(줄)
        if all(set(c) <= set("-: ") for c in 칸):
            continue  # 구분선
        행 = {}
        for 이름, 값 in zip(머리, 칸):
            if 이름 in 근거표_열:
                행[근거표_열[이름]] = 값
        if "수치_원문" in 행:
            행["수치"] = _숫자(행["수치_원문"])
            행["계산값"] = "계산값" in 행["수치_원문"]
        행들.append(행)
    return 행들


def 경고_읽기(글: str) -> list[dict]:
    """경고 절의 '[W1 종류] 문구 (적용 근거: R01 · R02)' 줄. 적용 근거가 없어도 버리지 않는다."""
    목록 = []
    for 줄 in 절_꺼내기(글, "경고").splitlines():
        m = re.search(r"\[(W\d+)\s*([^\]]*)\]\s*(.*)", 줄)
        if not m:
            continue
        문구 = m.group(3)
        적용 = _R.findall(문구.split("적용 근거", 1)[1]) if "적용 근거" in 문구 else []
        목록.append({"경고ID": m.group(1), "종류": m.group(2).strip(), "문구": 문구.strip(), "적용근거ID": 적용})
    return 목록


def 미확인_모으기(글: str) -> list[str]:
    """[자료 필요] · 미확인 · 미확보가 들어간 줄 (중복 제거, 순서 유지)."""
    줄들 = [줄.strip(" -|") for 줄 in 글.splitlines() if re.search(r"\[자료 필요|미확인|미확보", 줄)]
    return list(dict.fromkeys(줄 for 줄 in 줄들 if 줄))


# ---------- 3단계 전달 ----------

def 전달_준비(조건: dict, 확정체류기간: str, 선택_E3: str, 결과2: str, 기관데이터: str) -> dict:
    """3단계로 넘길 입력 (단계_넘김.md 4장 초안 필드). 실제 3단계 호출은 아직 연결 전."""
    return {
        "단계": 2,
        "조건": {
            "방문객": "외국인",
            "시기": 계절_월[조건["계절"]],
            "계절": 조건["계절"],
            "언어권": list(조건["언어권"]),
            "지역": list(조건["지역"]),
            "체류기간": 조건["체류기간"],
        },
        "확정체류기간": 확정체류기간,
        "담당자선택_E3": 선택_E3,
        "요약": 절_꺼내기(결과2, "수요 분석 요약"),
        "추천": 절_꺼내기(결과2, "체류 기간 추천"),
        "근거목록": 근거표_읽기(결과2),
        "경고목록": 경고_읽기(결과2),
        "대구도착출발지점": "미확보",
        "미확인사항": 미확인_모으기(결과2) + ([] if "있음" in 기관데이터 else ["기관 데이터 없음"]),
        "담당자판단": {"채택근거ID": [], "비고": "초안 · 3단계 담당과 공동 확인 전"},
        "기관데이터": 기관데이터,
        "2단계결과_원문": 결과2,
        "필드상태": "초안 (단계_넘김.md 4장, 3단계 담당과 형식 합의 전)",
    }


def _중복(목록: list[str]) -> list[str]:
    본것, 중복 = set(), []
    for x in 목록:
        if x in 본것 and x not in 중복:
            중복.append(x)
        본것.add(x)
    return 중복


def 전달_검사(전달: dict) -> list[str]:
    """문제 목록. 빈 목록이면 통과. 단계_넘김.md 5장 중 지금 검사할 수 있는 것."""
    문제 = []
    for 칸 in ["조건", "확정체류기간", "담당자선택_E3", "요약", "근거목록", "경고목록", "미확인사항"]:
        if 칸 not in 전달:
            문제.append(f"필수 필드 없음: {칸}")
    if 문제:
        return 문제

    빠짐 = 빠진_조건(전달["조건"])
    if 빠짐:
        문제.append("조건 누락: " + ", ".join(빠짐))
    if 전달["확정체류기간"] not in 확정체류기간_선택지:
        문제.append("확정 체류 기간 미선택 — 3단계를 시작하지 않고 담당자에게 되묻는다")
    if 전달["담당자선택_E3"] != "경고를남기고진행":
        문제.append("2단계 담당자 선택(E3) 미선택 — 3단계를 시작하지 않는다")
    if not 전달["요약"]:
        문제.append("수요 분석 요약을 찾지 못함")

    근거목록 = 전달["근거목록"]
    if not 근거목록:
        문제.append("근거표를 찾지 못함 — '## 근거표' 절의 표가 있는지 확인")
    근거ID = [행.get("근거ID", "") for 행 in 근거목록]
    for 중 in _중복(근거ID):
        문제.append(f"근거 ID 중복: {중}")
    for 행 in 근거목록:
        이름 = 행.get("근거ID") or "(ID 없음)"
        if not _R.fullmatch(행.get("근거ID", "")):
            문제.append(f"{이름}: 근거 ID 형식이 R+숫자가 아님")
        빠진칸 = [칸 for 칸 in 근거_필수 if not 행.get(칸)]
        if 빠진칸:
            문제.append(f"{이름}: 필수 칸 없음 ({', '.join(빠진칸)})")
        if 행.get("수치") == "미확인":
            문제.append(f"{이름}: 수치가 숫자 하나가 아님 ({행.get('수치_원문', '')})")

    경고ID = [w["경고ID"] for w in 전달["경고목록"]]
    for 중 in _중복(경고ID):
        문제.append(f"경고 ID 중복: {중}")
    있는근거 = set(근거ID)
    for w in 전달["경고목록"]:
        if not w["적용근거ID"]:
            문제.append(f"{w['경고ID']}: 적용 근거 ID 없음 (연결 누락)")
        없음 = [r for r in w["적용근거ID"] if r not in 있는근거]
        if 없음:
            문제.append(f"{w['경고ID']}: 근거표에 없는 근거 ID {', '.join(없음)}")
    return 문제
