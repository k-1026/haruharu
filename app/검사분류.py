"""검사 결과를 세 가지로 나눈다. AI 호출 없음.

- AI수정: 자료는 있는데 코스가 틀린 것(시간 겹침·형식 오류·경고 누락 등). 코스 에이전트가 고치고 다시 검사한다.
- 자료보완: 자료가 없어서 생긴 것(좌표·운영정보 미확인, 후보 없음 등). 수집 에이전트가 찾고, 못 찾으면 부족하다고 남긴다.
- 사람결정: 담당자만 정할 수 있는 것(시작·종료, 2일차 오전, 식사 방식, 확정). 미정으로 두고 마지막 검토에 모은다.

모르는 문구는 사람결정으로 둔다. AI가 임의로 고치는 것보다 사람이 보는 편이 안전하기 때문이다.
"""
import 기획기록 as 기록모듈
from 시간표검사 import 시간표_검사
from 운영검토 import 출발가능요일

종류 = ['AI수정', '자료보완', '사람결정']

# 순서가 중요하다: 앞쪽 규칙이 먼저 맞는다
_규칙 = [
    ('AI수정', ['변경 금지', '일정 겹침', '형식 오류', '경고 필요', '경고 누락', '중복', '없는 근거ID', '일차 오류', '시각 오류',
              '지원하지 않는 일차', '시작 전입니다', '종료 후입니다', '종료 시각을 넘', '머무는 시간 미정', '비어 있음', '칸ID 없음',
              '대상 칸ID', '확정 식당이 있음', '식당 없음', '휴무', '운영시간 밖']),
    ('사람결정', ['확정조건 미충족', '담당자', '선택 대기', '입력 대기', '미선택', '미확정', '정한 뒤', '시각 미정']),
    ('자료보완', ['좌표 미확인', '운영정보', '운영 정보', '못 찾음', '근거 없음', '출처', '후보 없음', '미확인']),
]


def 문구_분류(문구):
    for 이름, 말들 in _규칙:
        if any(말 in 문구 for 말 in 말들):
            return 이름
    return '사람결정'


def 담당자_미정_문구(문구, 조건):
    """시작·종료·운영방식을 담당자가 아직 정하지 않아 나온 형식 문구는 'AI가 고칠 것'이 아니다.
    관리자 화면 결과검사와 같게 담당자 입력 대기 문구로 바꿔 사람결정으로 보낸다."""
    미정 = ('', '미확인', '미정', '미선택', None)
    for 접두 in ['시작', '종료']:
        if 문구 == f'{접두}시각 형식 오류' and 조건.get(접두 + '시각') in 미정:
            return f'{접두} 시각 담당자 입력 대기'
        if 문구 == f'{접두}지점 미확정' and 조건.get(접두 + '지점') in 미정:
            return f'{접두} 장소 담당자 입력 대기'
    if 문구 == '운영방식 형식 오류' and 조건.get('운영방식') in 미정:
        return '운영 방식 담당자 선택 대기'
    return 문구


def 빈분류():
    return {k: [] for k in 종류}


def _넣기(분류, 이름, 문구, 출처):
    if 문구 and not any(x['문구'] == 문구 for x in 분류[이름]):
        분류[이름].append({'문구': 문구, '출처': 출처})


def 나누기(코드문제=(), 시간표=None, 검증문제=()):
    """코드 검사 문구·시간표 검사·검증 에이전트 문제를 세 가지로 나눈다."""
    분류 = 빈분류()
    for 문구 in 코드문제:
        _넣기(분류, 문구_분류(문구), 문구, '형식 검사')
    if 시간표:
        for 문구 in 시간표.get('충돌', []):
            _넣기(분류, 'AI수정', 문구, '시간표 검사')
        for 문구 in 시간표.get('확인대기', []):
            _넣기(분류, 문구_분류(문구), 문구, '시간표 검사')
    for x in 검증문제:
        곳 = x.get('되돌릴곳')
        이름 = {'코스': 'AI수정', '수집': '자료보완'}.get(곳, '사람결정')
        _넣기(분류, 이름, x.get('문구') or x.get('내용', ''), '검증 에이전트')
    return 분류


def 안_검사(기록, 안id, 입력=None, 작성자='코드:점검'):
    """최신 버전을 코드로 검사해 분류하고 기록에 남긴다. 입력(3단계 입력)이 있으면 형식 검사도 한다."""
    안 = max([x for x in 기록['코스안'] if x.get('안id') == 안id], key=lambda x: x.get('버전', 1))
    버전 = 안.get('버전', 1)
    코스 = 안['코스']
    조건 = (입력 or {}).get('코스작성조건') or 기록['조건'].get('코스작성조건', {})
    체류 = (입력 or {}).get('확정체류기간') or 기록['조건'].get('체류기간', '당일')
    try:
        표 = 시간표_검사(코스, 조건, 체류)
    except (TypeError, ValueError, KeyError, AttributeError):
        표 = {'충돌': [], '확인대기': ['시간표 형식을 읽지 못해 시간 검사를 하지 못함']}
    코드문제 = []
    if 입력 and isinstance(입력.get('코스작성조건'), dict):  # 3단계 입력이 있을 때만 형식 검사(가져온 기존 시험·화면 실행)
        from 단계연결 import 코스_검사
        try:
            코드문제 = 코스_검사(코스, 입력)
        except (TypeError, ValueError, KeyError, AttributeError):
            코드문제 = ['코스 필수 필드 형식 오류']
    try:
        days = 출발가능요일(코스, 코스.get('운영검토기록') or {}, None, 조건)['안별']
        가능 = days.get('공통') if '공통' in days else next(iter(days.values()), None)
    except Exception:
        가능 = None
    코드문제 = [담당자_미정_문구(x, 조건) for x in 코드문제]
    분류 = 나누기(코드문제, 표)
    from 기획기준 import 필수조건반영
    for 항목 in 필수조건반영(코스, 기록모듈.적용조건(기록, 안id)['조건']):
        if 항목.get('반영') in ['못지킴', '미확인']:
            이름 = 'AI수정' if 항목['반영'] == '못지킴' else '자료보완'
            _넣기(분류, 이름, f"필수 조건 {항목['조건']} {항목['반영']}: {항목['이유']}", '필수 조건 검사')
    for 희망 in 코스.get('희망반영') or []:   # 코스 에이전트가 지키지 못한 희망과 이유
        if isinstance(희망, dict) and 희망.get('반영') in ['못지킴', '일부']:
            _넣기(분류, '사람결정', f"희망 '{희망.get('내용', '')}' {희망.get('반영')}: {희망.get('이유', '이유 없음')}", '코스 에이전트')
    문구 = f"출발 가능 요일: {' · '.join(가능) if 가능 else '없음'} / AI 수정 {len(분류['AI수정'])} · 자료 보완 {len(분류['자료보완'])} · 사람 결정 {len(분류['사람결정'])}"
    기록모듈.추가(기록, '경고', {'종류': '코드점검', '안id': 안id, '버전': 버전, '문구': 문구,
                           '결과': {'출발가능요일': 가능, '시간표': {'충돌': 표['충돌'], '확인대기': 표['확인대기']}}, '분류': 분류},
               작성자, '시간표·형식·요일 검사')
    기록모듈.실행_기록(기록, 작성자, '점검', 안id, f'{안id}안 {버전}버전 코드 검사', '성공', AI호출=0)
    return 분류


def 최신분류(기록, 안id, 버전):
    """그 안·버전의 코드 검사 분류 + 검증 에이전트 문제를 합친 것."""
    코드 = next((x for x in reversed(기록['경고']) if x.get('종류') == '코드점검' and x.get('안id') == 안id
               and x.get('버전', 1) == 버전 and x.get('분류')), None)
    분류 = {k: list(v) for k, v in (코드['분류'] if 코드 else 빈분류()).items()}
    검증 = [x for x in 기록['경고'] if x.get('종류') == '검증' and x.get('안id') == 안id and x.get('버전', 1) == 버전]
    for 이름, 묶음 in 나누기(검증문제=검증).items():
        for x in 묶음:
            _넣기(분류, 이름, x['문구'], x['출처'])
    return 분류
