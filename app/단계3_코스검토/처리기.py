def 주문요청(입력,후보표,이전코스=None):
    """코스 에이전트에 줄 짧은 입력: 조건·요청 + 코드가 고른 후보표. 근거 원문·지침 전문·이전 완성 코스는 보내지 않는다."""
    from app.단계3_코스검토.코스조립 import 이전_주문서, 후보표_글
    요청={k:입력[k] for k in 주문요청키 if k in 입력}
    if 이전코스:요청['이전주문서']=이전_주문서(이전코스,후보표)
    요청['형식']='한 안 주문서 {"안":{...}} JSON 하나로 답한다. 후보표의 P·R·O 번호만 쓴다.'
    if 입력.get('희망'):요청['형식']+=' 입력 희망마다 안 안에 "희망반영"을 쓴다.'
    if any('대안설명' in x for x in 입력.get('출력추가') or []):요청['형식']+=' 원래 요청과 다른 안이므로 안 안에 "대안설명"을 쓴다.'
    요청['후보표']=후보표_글(후보표)
    return 요청


def 코스짜기(기록,안id,runs루트,보완요청,실행함수=None,추가입력=None,다듬기=None,유지시간칸=None):
    """AI는 주문서(장소 번호·머무는 시간·근거)만 쓰고, 코드가 완성 코스로 조립해 새 버전으로 남긴다."""
    from app.단계3_코스검토.코스조립 import 후보표_만들기, 조립, 주문지침
    입력=코스입력(기록,안id,runs루트,보완요청)
    if 추가입력:입력.update(추가입력)
    이전=입력.get('이전코스')
    버전=max(기록모듈.버전목록(기록,안id),default=0)+1
    대상=f'{안id}안 {버전}버전'
    표=후보표_만들기(입력,이전)
    값=호출(기록,'에이전트:코스',주문지침,'코스',대상,주문요청(입력,표,이전),'코스안 작성' if not 보완요청 else '보완 요청 반영',실행함수)
    if 값 is None:return False
    값,문제=조립(값,표,입력,이전,유지시간칸)
    if 문제:
        기록모듈.실행_기록(기록,'에이전트:코스','코스',대상,('주문서 문제: '+'; '.join(문제))[:300],'실패')
        return False
    수정 = 입력.get('부분수정') or {}
    if '바꿀칸ID' in 수정:
        from app.단계3_코스검토.코스편집 import 변경_비교
        변경 = 변경_비교(이전, 값)
        if not 변경:
            기록모듈.실행_기록(기록,'에이전트:코스','코스',대상,'요청한 범위에 실제 변경이 없습니다. 요청 또는 수정 범위를 조정해 주세요.','실패')
            return False
        값['부분수정기록'] = {**수정, '이전버전': 입력.get('이전버전'), '변경목록': 변경,
                         '안내': '실제 변경 내역입니다. 자유 요청의 의도와 운영·이동 조건은 담당자가 다시 확인해 주세요.'}
    if 다듬기:값=다듬기(값)
    from app.단계1_기획조건.기획기준 import 필수조건반영
    값['필수조건반영']=필수조건반영(값,입력['조건'])
    같은안=[x for x in 기록['코스안'] if x.get('안id')==안id]
    if 같은안:
        이전=max(같은안,key=lambda x:x.get('버전',1))['코스']
        빠진=[k for k in 필수필드 if k in 이전 and k not in 값]
        # 코드가 만들지 못하는 기록(장소 스토리·대체 이력·담당자 결정)은 비어 있으면 이전 버전 것을 이어받는다
        빠진+=[k for k in ['장소스토리','대체이력','담당자결정'] if 이전.get(k) and not 값.get(k) and k not in 빠진]
        if 빠진:  # AI가 고쳐 쓰며 빠뜨린 필드는 이전 버전 값을 그대로 이어받는다(새로 만들지 않음)
            값={**값,**{k:이전[k] for k in 빠진},'이어받은필드':빠진}
    버전=max(기록모듈.버전목록(기록,안id),default=0)+1
    기록모듈.추가(기록,'코스안',{'안id':안id,'코스':값,'버전':버전,'보완요청':list(보완요청)},'에이전트:코스','; '.join(보완요청))
    선택=기록.get('선택')
    if 선택 and 선택.get('안id')==안id:
        선택['다시확인필요']=f'{안id}안 {버전}버전이 새로 생김. 선택한 {선택["버전"]}버전의 확인은 새 버전에 이어지지 않음'
    return True


def _칸키(r):
    return (r.get('일차'),r.get('시간칸'))


def 유지칸_되살리기(이전,새,유지시간칸):
    """유지하기로 한 시간칸은 이전 버전 그대로 둔다. AI가 바꿨어도 코드가 되돌리고 몇 칸을 되돌렸는지 남긴다."""
    이전칸=이전.get('칸목록') or [];새칸=새.get('칸목록') or []
    out=[];쓴=set()
    for r in 이전칸:
        if r.get('시간칸') in 유지시간칸:
            out.append(r)
        elif _칸키(r) not in 쓴:
            out+=[n for n in 새칸 if _칸키(n)==_칸키(r)];쓴.add(_칸키(r))
    out+=[n for n in 새칸 if _칸키(n) not in 쓴 and n.get('시간칸') not in 유지시간칸 and n not in out]
    되돌림=sum(1 for r in 이전칸 if r.get('시간칸') in 유지시간칸 and r not in 새칸)
    유지ID={r.get('칸ID') for r in 이전칸 if r.get('시간칸') in 유지시간칸}
    식사=[m for m in 이전.get('식사목록') or [] if m.get('칸ID') in 유지ID]+[m for m in 새.get('식사목록') or [] if m.get('칸ID') not in 유지ID]
    return {**새,'칸목록':out,'식사목록':식사},되돌림


