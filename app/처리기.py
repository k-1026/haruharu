    if 적용['바꾼조건']:입력['자료재검토필요']=f"꼭 지킬 조건을 바꾼 안({', '.join(적용['바꾼조건'])}): 바탕 근거가 이 조건에 맞는지 다시 확인해야 함"
    같은안=[x for x in 기록['코스안'] if x.get('안id')==안id]
