class AI총괄시험(unittest.TestCase):
    def 준비(self):
        r = 기록()
        기록모듈.추가(r, '코스안', {'안id': 'A', '버전': 1, '코스': 기본코스}, '에이전트:코스')
        검사분류.안_검사(r, 'A')
        return r

    def test_AI가_고른_검증을_따른다(self):
        r = self.준비()
        d = 총괄.AI_다음_할일(r, lambda p, i: '{"행동":"검증","대상":"A","이유":"점검 끝, 검증 전"}')
        self.assertEqual((d['행동'], d['판단']), ('검증', 'AI'))
        self.assertEqual(r['실행'][-1]['에이전트'], '에이전트:총괄')   # 총괄 호출도 실행 기록·한도에 들어감
        self.assertEqual(r['실행'][-1]['AI호출'], 1)

    def test_규칙에_어긋난_답은_거부하고_규칙으로(self):
        r = self.준비()
        for 답, 이유 in [('{"행동":"홍보","대상":"A"}', '고를 수 없는 일'), ('{"행동":"검증","대상":"Z"}', '없는 안'),
                       ('{"행동":"대안","바꿀희망":{"희망-9":"?"},"이유":"x"}', '없는 희망'),
                       ('{"행동":"대안","바꿀희망":{"희망-1":"저녁은 중구"}}', '이유가 필요')]:
            with self.subTest(답=답):
                d = 총괄.AI_다음_할일(r, lambda p, i, 답=답: 답)
                self.assertEqual(d['판단'], '규칙');self.assertIn(이유, d['이유'])
                self.assertEqual(d['행동'], '검증')   # 규칙 총괄의 답

    def test_AI응답이_없으면_규칙으로(self):
        r = self.준비()
        def 실패(p, i):
            raise RuntimeError('네트워크')
        d = 총괄.AI_다음_할일(r, 실패)
        self.assertEqual((d['행동'], d['판단']), ('검증', '규칙'))

    def test_대안은_한번만(self):
        r = self.준비()
        self.assertIn('대안', 총괄.상황(r)['할수있는일'])
        기록모듈.안_추가(r, 'B', '대안', '에이전트:총괄', 바꾼희망={'희망-1': '저녁은 중구'}, 이유='이동')
        self.assertNotIn('대안', 총괄.상황(r)['할수있는일'])


class 끝까지시험(unittest.TestCase):
    def test_AI총괄이_검증_대안_마침을_지휘하고_B안에_이유가_붙는다(self):
        r = 기록()
        기록모듈.추가(r, '코스안', {'안id': 'A', '버전': 1, '코스': {**기본코스, '희망반영': [
            {'희망id': '희망-1', '내용': '저녁은 동구 평화시장 닭똥집골목', '반영': '일부', '이유': '야경과 이어지지 않음'}]}}, '에이전트:코스')
        결정 = iter(['{"행동":"점검","대상":"A","이유":"점검 전"}', '{"행동":"검증","대상":"A","이유":"검증 전"}',
                   '{"행동":"대안","바꿀희망":{"희망-1":"저녁은 중구 동성로 닭요리"},"이유":"동구 저녁은 야경 동선과 끊김"}',
                   '{"행동":"점검","대상":"B","이유":"B안 점검"}', '{"행동":"검증","대상":"B","이유":"B안 검증"}',
                   '{"행동":"담당자에게","이유":"남은 것은 담당자 결정"}'])
        본입력 = []

        def fn(p, i):
            if p.endswith('총괄.md'):
                return next(결정)
            if p.endswith('검증.md'):
                return '{"통과":true,"문제":[]}'
            본입력.append(json.loads(i))
            return json.dumps({'안': {'칸': [{'칸ID': 'd1', '일차': 1, '시간칸': '낮', '장소': 'P1', '머무는분': 60, '근거': [], '운영': [], '이유': ''},
                                            {'칸ID': 'e1', '일차': 1, '시간칸': '저녁', '장소': 'P6', '머무는분': 60, '근거': [], '운영': [], '이유': ''}],
                                     '식사': [], '대안설명': {'무엇을': '저녁을 중구로', '왜': '야경 동선', '좋아진점': '이동 줄어듦', '남은문제': '없음'},
                                     '희망반영': [{'희망id': '희망-1', '반영': '지킴', '이유': ''}]}}, ensure_ascii=False)
        알림 = []
        steps = 총괄.돌리기(r, Path('.'), fn, AI판단=True, 알림=lambda k, d: 알림.append((k, d['행동'])))
        self.assertEqual([s['행동'] for s in steps], ['점검', '검증', '대안', '점검', '검증', '담당자에게'])
        b = 기록모듈.안_찾기(r, 'B')
        self.assertEqual(b['바꾼희망'], {'희망-1': '저녁은 중구 동성로 닭요리'});self.assertIn('야경', b['이유'])
        self.assertEqual(본입력[0]['안']['안id'], 'B');self.assertIn('대안설명', 본입력[0]['형식'])
        정리 = 총괄.정리(r)
        self.assertEqual([a['안id'] for a in 정리['안']], ['A', 'B'])
        self.assertEqual(정리['안'][1]['대안설명']['왜'], '야경 동선')
        self.assertTrue(any('일부: 야경과 이어지지 않음' in x for x in 정리['사람이정할것']))
        self.assertIn(('시작', '판단'), 알림)


class 부분수정시험(unittest.TestCase):
    def test_유지칸은_AI가_바꿔도_코드가_되돌리고_새버전으로(self):
        r = 기록()
        기록모듈.추가(r, '코스안', {'안id': 'A', '버전': 1, '코스': 기본코스}, '에이전트:코스')
        기록모듈.선택(r, 'A', 1, '사람:담당자')
        본 = {}

        def fn(p, i):
            본['입력'] = json.loads(i)
            # AI가 낮(유지)까지 바꿔 버린 주문서: 코드는 낮을 이전 그대로 두고 센다
            주 = lambda id, t, p: {'칸ID': id, '일차': 1, '시간칸': t, '장소': p, '머무는분': 60, '근거': [], '운영': [], '이유': ''}
            return json.dumps({'안': {'칸': [주('d1', '낮', 'P3'), 주('e1', '저녁', 'P6'), 주('n1', '밤', 'P9')],
                                     '식사': [{'칸ID': 'e1', '방식': '지정식', '권역': 'P6', '후보': []}]}}, ensure_ascii=False)
        self.assertTrue(처리기.부분수정(r, 'A', Path('.'), ['낮', '점심'], ['저녁'], '중구에서 치킨을 고를 수 있게', fn))
        self.assertEqual(기록모듈.버전목록(r, 'A'), [1, 2])
        새 = 처리기.최신안(r, 'A')['코스']
        self.assertEqual([c['장소명'] for c in 새['칸목록'] if c['시간칸'] != '숙박'],
                         ['대구광역시 중구 근대골목', '대구광역시 중구 서문시장', '대구광역시 중구 산호찜갈비', '대구광역시 중구 서문시장 야시장'])
        self.assertEqual(새['부분수정기록']['코드가_되돌린_유지칸'], 1)
        self.assertEqual({m['칸ID'] for m in 새['식사목록']}, {'l1', 'e1'})
        self.assertEqual(본['입력']['부분수정']['바꿀시간칸'], ['저녁'])
        self.assertEqual(r['코스안'][0]['코스']['칸목록'][0]['장소명'], '근대골목')   # 이전 버전은 그대로
        self.assertIn('다시확인필요', r['선택'])

    def test_잘못된_요청은_거부(self):
        r = 기록()
        기록모듈.추가(r, '코스안', {'안id': 'A', '버전': 1, '코스': 기본코스}, '에이전트:코스')
        for 유지, 바꿀, 요청 in [([], ['숙박'], 'x'), (['저녁'], ['저녁'], 'x'), ([], ['저녁'], '')]:
            with self.subTest(바꿀=바꿀), self.assertRaises(ValueError):
                처리기.부분수정(r, 'A', Path('.'), 유지, 바꿀, 요청, lambda p, i: '{}')

