import 기획기록 as 기록모듈
from 운영검토 import 출발가능요일
from 시간표검사 import 시간표_검사


def _안(기록,안id):
    같은안=[x for x in 기록['코스안'] if x.get('안id')==안id]
    if not 같은안:raise ValueError(f'없는 코스안: {안id}')
    return max(같은안,key=lambda x:x.get('버전',1))


def 코스_점검(기록,안id,작성자='코드:점검'):
    안=_안(기록,안id);코스=안['코스'];조건=기록['조건'].get('코스작성조건',{})
    days=출발가능요일(코스,코스.get('운영검토기록') or {},None,조건)['안별']
    가능=days.get('공통') if '공통' in days else next(iter(days.values()),None)
    표=시간표_검사(코스,조건,기록['조건'].get('체류기간','당일'))
    out={'출발가능요일':가능,'시간표':{'충돌':표['충돌'],'확인대기':표['확인대기']}}
    문구=f"출발 가능 요일: {' · '.join(가능) if 가능 else '없음'} / 시간 충돌 {len(표['충돌'])}건 · 확인 대기 {len(표['확인대기'])}건"
    기록모듈.추가(기록,'경고',{'종류':'코드점검','안id':안id,'버전':안.get('버전',1),'문구':문구,'결과':out},작성자,'요일 검사·시간표 검사')
    기록모듈.실행_기록(기록,작성자,'점검',안id,'코스안 요일·시간표 점검','성공',AI호출=0)
    return out
