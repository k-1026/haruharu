"""담당자의 명시적 시작·종료/2일차 점심 수정만 반영한다. AI·동선 계산 없음."""
import copy


def 수정본_만들기(기존, 이전조건, 조건):
    결과 = copy.deepcopy(기존)
    if isinstance(결과.get('운영검토기록'),dict):
        결과['운영검토기록']['담당자최종확인']=False
        결과['담당자최종확인기록']={'확인':False,'사유':'코스 조건 변경으로 재검토 필요'}
        for row in 결과['운영검토기록'].get('일정확인',[]):row['연결확인']=False
        for row in 결과['운영검토기록'].get('운영확인',[]):row['방문일운영확인']=False
    수정 = []
    재검토 = []
    끝 = 결과.setdefault('코스시작종료', {})
    for 이름 in ['시작일차','시작지점', '시작시각','종료일차', '종료지점', '종료시각']:
        미정='미정' if '일차' in 이름 else '미확인'
        if 조건[이름] != 이전조건.get(이름, 미정):
            수정.append(f'{이름}: {이전조건.get(이름, 미정)} → {조건[이름]}')
        끝[이름] = 조건[이름]
    if 수정:
        재검토.append('시작·종료 조건 변경: 첫·마지막 일정의 연결, 이동 구간, 영업시간을 다시 확인하세요.')
    옛기록 = {'시작종료': copy.deepcopy(기존.get('코스시작종료', {})),
             '확정조건': copy.deepcopy(기존.get('확정조건', {})),
             '담당자결정': 결과.get('담당자결정', []), '체크리스트': copy.deepcopy(결과.get('체크리스트', [])),
             '식사목록':copy.deepcopy(결과.get('식사목록',[]))}
    끝.pop('후보', None)
    끝['상태'] = '담당자 조건 반영 · 동선 재검토 전'
    결과.setdefault('확정조건', {})['시작종료확정'] = False
    결과['확정조건']['메모'] = '수정 사항은 반영했으나 코스 전체를 확정하지 않았습니다.'
    포함 = 조건['2일차점심포함']
    수정.append('2일차 점심 포함 여부: ' + 포함)
    칸들, 식사들 = 결과['칸목록'], 결과['식사목록']
    점심키 = {(r.get('안', '공통'), r['칸ID']) for r in 칸들 if r.get('일차') == 2 and r.get('시간칸') == '점심'}
    if 포함 == '미포함':
        결과['칸목록'] = [r for r in 칸들 if (r.get('안', '공통'), r['칸ID']) not in 점심키]
        결과['식사목록'] = [r for r in 식사들 if (r.get('안', '공통'), r['칸ID']) not in 점심키]
        옛기록['제외한점심칸'] = [r for r in 칸들 if (r.get('안', '공통'), r['칸ID']) in 점심키]
        # 제외된 칸의 메모를 현행 참조로 남기지 않되 이전 기록은 보존한다.
        미확인 = 결과.get('미확인사항', [])
        옛기록['제외한칸의메모'] = [r for r in 미확인 if (r.get('안', '공통'), r.get('칸ID', r.get('대상 칸ID'))) in 점심키]
        결과['미확인사항'] = [r for r in 미확인 if r not in 옛기록['제외한칸의메모']]
    elif 포함 == '포함':
        선택 = next(r for r in 조건['식사목록'] if r['일차'] == 2 and r['시간칸'] == '점심')
        안들 = list(dict.fromkeys(r.get('안', '공통') for r in 칸들)) or ['공통']
        for 안 in 안들:
            대상 = [r for r in 칸들 if r.get('안', '공통') == 안 and r.get('일차') == 2 and r.get('시간칸') == '점심']
            if not 대상:
                rid = '담당자-2일차점심'
                while any(r.get('안', '공통') == 안 and r.get('칸ID') == rid for r in 칸들):
                    rid += '-추가'
                row = {'안': 안, '칸ID': rid, '일차': 2, '시간칸': '점심',
                       '장소명': '2일차 점심 (권역 미정)', '시각': {'값': '', '종류': '미정'},
                       '머무는시간': '미확인', '근거ID': [], '운영주체후보': []}
                칸들.append(row)
                대상 = [row]
            for row in 대상:
                meal = next((r for r in 식사들 if (r.get('안', '공통'), r['칸ID']) == (안, row['칸ID'])), None)
                if meal is None:
                    meal = {'안': 안, '칸ID': row['칸ID'], '시각': copy.deepcopy(row['시각']), '권역': '미정',
                            '추천후보': [], '이동시간': {'분': '미확인', '적용조건': '담당자 입력 후 확인'}, '이후연결': '종료 장소까지 이동 재확인'}
                    식사들.append(meal)
                meal.update({'방식': 선택['방식'], '식비포함': 선택['식비포함'],
                             '식당': 선택['식당'] if 선택['방식'] == '지정식' else ''})
                if 선택['방식'] == '지정식' and 선택['식당'] != '미선택':
                    row['장소명'] = 선택['식당']
        재검토.append('2일차 점심을 포함했습니다. 식사 시각·권역·머무는 시간·종료 장소까지 이동을 확인하세요. 미정 값은 자동으로 채우지 않았습니다.')
    elif 포함 == '미정':
        재검토.append('2일차 점심 포함 여부를 선택하세요. 기존 시간표와 식사 선택은 유지했습니다.')
    from 시간조정 import 시간표_조정
    체류='1박2일' if 조건['2일차점심포함']!='해당없음' else '당일'
    시간조정=시간표_조정(결과,조건,체류)
    수정.extend(시간조정['변경목록']);재검토.extend(시간조정['확인사항'])
    결과['수정전AI기록'] = 옛기록
    결과['담당자결정'] = [{'항목': '코스 조건 수동 수정', '선택': ' / '.join(수정), '입력경로': '관리자 화면'}]
    for row in 결과.get('체크리스트', []):
        row['결과'] = '재확인 필요'
    결과['코스수정기록'] = {'변경목록': 수정, '재검토항목': 재검토, 'AI재실행': False,
                         '시간조정':시간조정,
                         '기록시각': 조건['결정기록']['기록시각']}
    return 결과
